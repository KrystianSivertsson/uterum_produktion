/**
 * Applicerar inventeringen på produktlistan. Muterar inte input.
 * @returns {{ lista: object[], uppdaterade: number, nollade: string[], skapade: string[] }}
 */
export function appliceraInventering(produkter) {
  const lista = produkter.map(p => ({ ...p }));
  let uppdaterade = 0;
  const nollade = [];
  const skapade = [];
  for (const post of INVENTERING_POSTER) {
    const traffar = lista.filter(p => String(p.artikel || '').trim() === post.artikel);
    if (traffar.length === 0) {
      lista.push({
        id: 'inv2026_' + post.artikel.replace(/[^a-zA-Z0-9]+/g, '_'),
        namn: post.artikel + (post.detalj ? ' (' + post.detalj + ')' : ''),
        artikel: /^[0-9]+$/.test(post.artikel) ? post.artikel : '',
        antal: post.antal,
        minAntal: 5,
        kategori: 'Osorterat',
        enhet: post.enhet,
        ...(post.farger ? { farger: post.farger.map(f => ({ ...f })) } : {}),
      });
      skapade.push(post.artikel);
      continue;
    }
    // Huvudpost = högst saldo (först vid lika) — får hela inventeringsantalet
    const huvud = traffar.reduce((a, b) => ((b.antal || 0) > (a.antal || 0) ? b : a), traffar[0]);
    huvud.antal = post.antal;
    if (post.farger) huvud.farger = post.farger.map(f => ({ ...f }));
    uppdaterade++;
    for (const dubblett of traffar) {
      if (dubblett === huvud) continue;
      if ((dubblett.antal || 0) !== 0) nollade.push(dubblett.namn + ' (' + post.artikel + ')');
      dubblett.antal = 0;
      if (dubblett.farger?.length) dubblett.farger = [];
    }
  }
  return { lista, uppdaterade, nollade, skapade };
}
